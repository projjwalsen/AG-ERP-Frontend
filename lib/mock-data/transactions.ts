export interface MockStats {
  totalTransactions: number;
  pendingAuthentication: number;
  inwardPayments: number;
  outwardPayments: number;
  suspenseEntries: number;
  totalPendingAmount: number;
  todayPendingCount: number;
}

// Fixed "today" date to keep mock data deterministic for the workflow.
const MOCK_TODAY = "2026-05-31";

export function getMockStats(): MockStats {
  const pendingAuth = mockTransactions.filter(
    (t) => t.status === "PENDING_AUTHENTICATION"
  );
  const inward = mockTransactions.filter((t) => t.type === "INWARD");
  const outward = mockTransactions.filter((t) => t.type === "OUTWARD");
  const suspense = mockTransactions.filter((t) => t.isSuspense);

  const totalPendingAmount = pendingAuth.reduce((sum, t) => sum + t.amount, 0);
  const todayPendingCount = pendingAuth.filter(
    (t) => t.voucherDate === MOCK_TODAY
  ).length;

  return {
    totalTransactions: mockTransactions.length,
    pendingAuthentication: pendingAuth.length,
    inwardPayments: inward.length,
    outwardPayments: outward.length,
    suspenseEntries: suspense.length,
    totalPendingAmount,
    todayPendingCount,
  };
}
